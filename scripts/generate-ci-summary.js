#!/usr/bin/env node

const fs = require('fs');

/**
 * Generate a CI summary report for pull requests
 */
async function generateCISummary() {
  const summary = {
    timestamp: new Date().toISOString(),
    project: 'polly-id3',
    ci: {},
  };

  try {
    // Check test results
    if (fs.existsSync('coverage/coverage-summary.json')) {
      const coverage = JSON.parse(fs.readFileSync('coverage/coverage-summary.json', 'utf8'));
      summary.ci.testCoverage = {
        lines: coverage.total.lines.pct,
        functions: coverage.total.functions.pct,
        branches: coverage.total.branches.pct,
        statements: coverage.total.statements.pct,
      };
    }

    // Check quality report if available
    if (fs.existsSync('quality-report.json')) {
      const quality = JSON.parse(fs.readFileSync('quality-report.json', 'utf8'));
      summary.ci.qualityScore = quality.quality.overallScore;
      summary.ci.qualityDetails = quality.quality;
    }

    // Check for build artifacts
    summary.ci.buildStatus = {
      hasServerless: fs.existsSync('.serverless'),
      hasPackageLock: fs.existsSync('package-lock.json'),
    };

    // Check for test artifacts
    summary.ci.testStatus = {
      hasCoverage: fs.existsSync('coverage'),
    };

    // Generate markdown summary
    const markdown = generateMarkdownSummary(summary);
    fs.writeFileSync('ci-summary.md', markdown);

    console.log('CI summary generated successfully');
    return summary;
  } catch (error) {
    console.error('Error generating CI summary:', error);
    throw error;
  }
}

function generateMarkdownSummary(summary) {
  const coverage = summary.ci.testCoverage;
  const quality = summary.ci.qualityScore;
  const build = summary.ci.buildStatus;
  const tests = summary.ci.testStatus;

  return `# CI Summary Report

**Generated:** ${new Date(summary.timestamp).toLocaleString()}
**Project:** ${summary.project}

## 🧪 Test Results
${
  coverage
    ? `
✅ **Coverage Achieved:**
- **Lines:** ${coverage.lines}%
- **Functions:** ${coverage.functions}%
- **Branches:** ${coverage.branches}%
- **Statements:** ${coverage.statements}%

${
  coverage.lines >= 80 &&
  coverage.functions >= 80 &&
  coverage.branches >= 80 &&
  coverage.statements >= 80
    ? '🎯 **All coverage thresholds met!**'
    : '⚠️ **Some coverage thresholds not met**'
}
`
    : '❌ **No coverage data available**'
}

## 🎯 Quality Metrics
${
  quality
    ? `
**Overall Quality Score:** ${quality.toFixed(1)}%
${quality >= 80 ? '✅ **Excellent quality!**' : quality >= 60 ? '⚠️ **Good quality**' : '❌ **Quality needs improvement**'}
`
    : '❌ **No quality data available**'
}

## 🏗️ Build Status
${build.hasServerless ? '✅' : '❌'} Serverless artifacts
${build.hasPackageLock ? '✅' : '❌'} Package lock file

## 🧪 Test Status
${tests.hasCoverage ? '✅' : '❌'} Coverage reports

## 📊 Summary
${
  coverage && quality
    ? `
This build achieved **${coverage.lines}% line coverage** and a **${quality.toFixed(1)}% quality score**.

${coverage.lines >= 80 && quality >= 80 ? '🚀 **Ready for deployment!**' : '⚠️ **Review recommended before deployment**'}
`
    : '❌ **Insufficient data for deployment decision**'
}

---
*Generated by GitHub Actions CI*
`;
}

// Run if called directly
if (require.main === module) {
  generateCISummary()
    .then(() => process.exit(0))
    .catch(() => process.exit(1));
}

module.exports = { generateCISummary };
